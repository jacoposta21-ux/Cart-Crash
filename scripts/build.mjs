// Builds dist/: copies the static game and writes dist/src/build.js.
// --target=crazygames: the portal build (loads the CrazyGames SDK v3, fit rules).
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, argValue } from './lib/util.mjs';

const target = argValue('target', 'web');
const out = join(ROOT, argValue('out', 'dist'));
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'src'), { recursive: true });
let html = readFileSync(join(ROOT, 'index.html'), 'utf8');
if (target === 'crazygames') {
  html = html.replace('<link rel="stylesheet" href="styles.css">',
    '<link rel="stylesheet" href="styles.css">\n  <script src="https://sdk.crazygames.com/crazygames-sdk-v3.js"></script>');
}
writeFileSync(join(out, 'index.html'), html);
for (const f of ['styles.css', 'privacy.html']) cpSync(join(ROOT, f), join(out, f));
for (const d of ['vendor', 'assets']) cpSync(join(ROOT, d), join(out, d), { recursive: true });
cpSync(join(ROOT, 'src'), join(out, 'src'), { recursive: true, filter: (p) => !p.endsWith('build.js') });
const build = { target, version: pkg.version, builtOn: new Date().toISOString().slice(0, 10) };
writeFileSync(join(out, 'src', 'build.js'), `// Generated by scripts/build.mjs. Do not edit.\nexport const BUILD = ${JSON.stringify(build)};\n`);
console.log(`built ${out} (${target})`);
